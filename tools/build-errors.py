#!/usr/bin/env python3
"""Build share/php-quickpatch/catalog/errors.tsv from srs/error-matrix.md.

Columns: code, http, key, severity, message_vi, message_en. Messages keep
their {placeholders}; the first quoted string of each cell is used.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs/php-quickpatch/srs/error-matrix.md')
DST = os.path.join(ROOT, 'share/php-quickpatch/catalog/errors.tsv')


def first_quoted(cell):
    m = re.search(r'"((?:[^"\\]|\\.)*)"', cell)
    text = m.group(1) if m else cell.strip()
    return re.sub(r'\s+', ' ', text.replace('`', '')).strip()


def split_row(line):
    # Split on " | " but not on "\|" (escaped pipes inside cells).
    cells = re.split(r'(?<!\\)\|', line.strip().strip('|'))
    return [c.strip().replace('\\|', '|') for c in cells]


def main():
    rows = {}
    for line in open(SRC, encoding='utf-8'):
        if not line.startswith('| `ERR-'):
            continue
        c = split_row(line)
        if len(c) < 8:
            continue
        code = c[0].strip('`')
        if not re.match(r'^ERR-[A-Z]+-\d{3}-\d{2,3}$', code):
            continue
        rows[code] = (code, c[1], c[3].strip('`'), c[7], first_quoted(c[4]), first_quoted(c[5]))
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, 'w', encoding='utf-8') as out:
        out.write('# code\thttp\tkey\tseverity\tmessage_vi\tmessage_en (generated by tools/build-errors.py)\n')
        for code in sorted(rows):
            out.write('\t'.join(x.replace('\t', ' ') for x in rows[code]) + '\n')
    print('%d codes -> %s' % (len(rows), os.path.relpath(DST, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
