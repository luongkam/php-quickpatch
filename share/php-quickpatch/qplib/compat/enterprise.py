def _roadmap(findings, further, b, today, lang):
    """Phases 0-3 with effort, start/end on working days, and the findings each one closes."""
    reg = sum(r['hours'][0] for r in b['effort']['rows'] if r['kind'] == 'regression_test'), \
        sum(r['hours'][1] for r in b['effort']['rows'] if r['kind'] == 'regression_test')
    buckets = [('ph0', [f for f in findings if f['severity'] == 'critical' or f['category'] == 'secrets']),
               ('ph1', [f for f in findings if f['severity'] == 'high' and f['category'] != 'secrets']),
               ('ph2', [f for f in findings if f['severity'] in ('medium', 'low') and f['category'] != 'secrets'])]
    phases, offset = [], 0
    for key, fs in buckets:
        lo = sum(f['effort'][0] for f in fs)
        hi = sum(f['effort'][1] for f in fs)
        if key == 'ph1':
            lo, hi = lo + reg[0] + 8, hi + reg[1] + 16           # regression tests, test stage, production via alias
        if not fs and key != 'ph1':
            continue
        days = max(1, int(-(-hi // 8)))
        phases.append({'key': key, 'ids': [f['id'] for f in fs], 'effort': [lo, hi], 'start_off': offset, 'days': days})
        offset += days
    lo = sum(x['effort'][0] for x in further) + 2
    hi = sum(x['effort'][1] for x in further) + 4
    days = max(1, int(-(-hi // 8)))
    phases.append({'key': 'ph3', 'ids': [x['id'] for x in further], 'effort': [lo, hi], 'start_off': offset, 'days': days})
    start = datetime.date(*map(int, today.split('-')))
    for p in phases:
        p['start'] = BR._workdays(start, p['start_off'] + 1).isoformat()
        p['end'] = BR._workdays(start, p['start_off'] + p['days']).isoformat()
    return phases


