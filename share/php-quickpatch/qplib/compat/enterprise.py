def _options(res, lang, b, golive):
    lc = res.get('lifecycle') or {}
    cur = res.get('current_branch')
    lam = any((p.get('deploy') or {}).get('kind') == 'lambda' for p in res['projects']) or \
        any(d['kind'] in ('lambda_runtime', 'cdk_runtime') for p in res['projects'] for d in p['declarations'])
    rows = []
    branches = lc.get('branches') or [x for x in (lc.get('current'), lc.get('target')) if x]
    if len(branches) == 2 and branches[0]['branch'] == branches[1]['branch']:
        branches = branches[:1]
    for br in branches:
        eol = br.get('eol_date')
        months = None
        if eol:
            months = max(0, (datetime.date(*map(int, eol.split('-'))) - datetime.date(*map(int, golive.split('-')))).days // 30)
        la = BR.LAMBDA_RUNTIMES.get(br['branch'])
        if br['branch'] == cur:
            ev = 'o_current' if br['status'] == 'EOL' else 'o_current_ok'
        elif br['status'] == 'EOL':
            ev = 'o_no'
        elif br['status'] in ('PRE_RELEASE', 'CURRENT') or not br.get('lts'):
            ev = 'o_pre'
        elif lam and not la:
            ev = 'o_nolambda'
        elif br['branch'] == lc.get('recommended'):
            ev = 'o_rec'
        elif months is not None and months < 12:
            ev = 'o_short'
        else:
            ev = 'o_ok'
        row = [('Node.js %s' % br['branch']) + (' (nodejs%s.x)' % br['branch'] if lam and la else ''), fmt_date(eol, lang)]
        if lam:
            row += [fmt_date(la[0], lang) if la else '-', fmt_date(la[2], lang) if la else '-']
        row += [t('months', lang, n=months) if months is not None else '-', (ev, t(ev, lang))]
        rows.append(row)
    head = [t('option', lang), t('node_eol', lang)] + ([t('lambda_dep', lang), t('lambda_bu', lang)] if lam else []) + \
        [t('support_left', lang), t('assessment', lang)]
    return head, rows


