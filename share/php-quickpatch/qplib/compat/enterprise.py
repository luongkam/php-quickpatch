def _assets(res):
    out = []
    for p in res['projects']:
        d = p.get('deploy') or {}
        kind = 't_lambda' if d.get('kind') == 'lambda' else ('t_static' if d.get('kind') == 'static_site' else 't_node')
        dep = ', '.join(d.get('functions') or d.get('buckets') or []) or '-'
        out.append({'name': BR.pname(p), 'kind': kind, 'deployed': dep, 'packages': p.get('packages') or 0,
                    'lockfile': p.get('lockfile') or '-', 'p': p})
    return out


def _advisories(v):
    out = []
    for aid, a in sorted((v.get('by_advisory') or {}).items()):
        cves = [x for x in a.get('aliases') or [] if x.startswith('CVE-')]
        out.append({'id': aid, 'cve': ', '.join(cves), 'severity': a.get('severity') or v['severity'],
                    'summary': a.get('summary') or '', 'fixed': ', '.join((a.get('fixed') or [])[-3:])})
    if not out:
        out = [{'id': x, 'cve': '', 'severity': v['severity'], 'summary': '', 'fixed': ''} for x in v['advisories']]
    return out


def _vulns(res):
    """{(package, version): {v, projects[], scope}} over the projects (scope: prod, static, dev)."""
    out = {}
    for p in res['projects']:
        static = (p.get('deploy') or {}).get('kind') == 'static_site'
        for v in p['vulnerabilities'] or []:
            k = (v['package'], v['version'])
            scope = 'dev' if v['dev'] else ('static' if static else 'prod')
            x = out.setdefault(k, {'v': v, 'projects': [], 'scope': scope})
            if BR.pname(p) not in x['projects']:
                x['projects'].append(BR.pname(p))
            if scope == 'prod':
                x['scope'] = 'prod'
    return out


def _rank(s):
    return SEV.index(s) if s in SEV else 9


def _workday_end(start, days):
    return BR._workdays(datetime.date(*map(int, start.split('-'))), max(1, days)).isoformat()


