def _clip(s, n):
    s = s or ''
    if len(s) <= n:
        return s
    return s[:n].rsplit(' ', 1)[0].rstrip(';,') + ' …'


def e(v):
    return html.escape('' if v is None else str(v), quote=True)


def _inline(s):
    """Escape, then show `code` spans."""
    return re.sub(r'`([^`]+)`', lambda m: '<code>%s</code>' % m.group(1), e(s))


def _sections_numbered(doc):
    n, out = 0, []
    for s in doc['sections']:
        if s.get('number') is False or s.get('appendix'):
            out.append((None, s))
        else:
            n += 1
            out.append((n, s))
    return out


def _cell_html(spec, i, c):
    if spec.get('sev') == i and c in SEV:
        return '<span class="sev %s">%s</span>' % (c, e(t(c, spec.get('_lang', 'en'))))
    if isinstance(c, tuple):
        return '<span class="st %s">%s</span>' % (e(c[0]), e(c[1]))
    return _inline(c)


def _table_html(spec, lang):
    spec = dict(spec, _lang=lang)
    cls = ' class="small"' if spec.get('small') else ''
    o = ['<table%s><thead><tr>%s</tr></thead><tbody>' % (cls, ''.join('<th>%s</th>' % e(h) for h in spec['head']))]
    for ri, row in enumerate(spec['rows']):
        tds = []
        for i, c in enumerate(row):
            klass = []
            if i in (spec.get('num') or ()):
                klass.append('n')
            if spec.get('heat') and 1 <= i <= 4 and c and ri < len(spec['rows']) - 1:
                klass.append('c%d' % i)
            tds.append('<td%s>%s</td>' % (' class="%s"' % ' '.join(klass) if klass else '', _cell_html(spec, i, c)))
        o.append('<tr>%s</tr>' % ''.join(tds))
    o.append('</tbody></table>')
    return ('<div class="heat">%s</div>' % ''.join(o)) if spec.get('heat') else ''.join(o)


def _finding_html(f, lang):
    def ul(xs):
        return '<ul>%s</ul>' % ''.join('<li>%s</li>' % _inline(x) for x in xs) if xs else '-'
    rows = [(t('category', lang), e(f['cat_label'])), (t('affected', lang), e(', '.join(f['affected']) or '-')),
            (t('observation', lang), ul(f['observation'])), (t('evidence', lang), ul(f['evidence'])),
            (t('impact', lang), _inline(f['impact'])), (t('recommendation', lang), ul(f['recommendation'])),
            (t('effort', lang), e(_hrs(f['effort'][0], f['effort'][1], lang)))]
    if f.get('due'):
        rows.append((t('due', lang), e('%s (%s)' % (fmt_date(f['due'], lang), t('days', lang, n=SLA_DAYS[f['severity']])))))
    if f.get('refs'):
        rows.append((t('references', lang), ul(f['refs'])))
    return ('<div class="finding" id="%s"><div class="hd"><span class="id">%s</span><span class="tt">%s</span>'
            '<span class="sev %s">%s</span></div><div class="bd"><dl>%s</dl></div></div>') % (
        e(f['id'].lower()), e(f['id']), e(f['title']), e(f['severity']), e(t(f['severity'], lang)),
        ''.join('<dt>%s</dt><dd>%s</dd>' % (k, v) for k, v in rows))


def _gantt_html(g, lang):
    total = max(1, g['total'])
    o = ['<div class="gantt">']
    for lbl, a, b2, k in g['rows']:
        o.append('<div class="row"><div class="lbl">%s</div><div class="track"><div class="bar %s" style="left:%.2f%%;width:%.2f%%"></div></div></div>' % (
            e(lbl), e(k), 100.0 * a / total, max(1.5, 100.0 * (b2 - a) / total)))
    start = datetime.date(*map(int, g['start'].split('-')))
    end = BR._workdays(start, total).isoformat()
    o.append('<div class="scale"><span>%s</span><span>%s</span><span>%s</span></div></div>' % (
        e(fmt_date(g['start'], lang)), e(t('days', lang, n=total)), e(fmt_date(end, lang))))
    return ''.join(o)


def render_html(doc):
    lang, m = doc['lang'], doc['meta']
    o = ['<!doctype html><html lang="%s"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
         '<title>%s — %s</title><style>%s</style></head><body>' % (e(lang), e(doc['title']), e(m['project']), CSS)]
    o.append('<section class="page cover"><div class="band"><div class="cls">%s</div><h1>%s</h1><p class="sub">%s</p></div>'
             '<div class="meta"><table>%s</table></div><div class="foot">%s<br>%s</div></section>' % (
                 e(m['classification']), e(doc['title']), e(doc['subtitle']),
                 ''.join('<tr><td>%s</td><td>%s</td></tr>' % (e(k), e(v)) for k, v in (
                     (t('client', lang), m['client']), (t('project', lang), m['project']), (t('doc_id', lang), m['doc_id']),
                     (t('version', lang), '%s — %s' % (m['version'], t('draft', lang))), (t('date', lang), fmt_date(m['date'], lang)),
                     (t('prepared_by', lang), m['prepared_by']), (t('classification', lang), m['classification']))),
                 e(t('conf_note', lang)), e(t('generated', lang, v=m['tool'], d=fmt_date(m['date'], lang)))))
    secs = _sections_numbered(doc)
    o.append('<section class="page toc"><h2>%s</h2><ol>%s</ol></section>' % (e(t('contents', lang)), ''.join(
        '<li><span>%s</span><a href="#%s">%s</a></li>' % (e(n or ''), e(s['id']), e(s['title'])) for n, s in secs)))
    for n, s in secs:
        o.append('<section class="page" id="%s"><h2>%s%s</h2>' % (e(s['id']), ('<span class="n">%d</span>' % n) if n else '', e(s['title'])))
        for blk in s['blocks']:
            k = blk[0]
            if k == 'h3':
                o.append('<h3>%s</h3>' % e(blk[1]))
            elif k == 'p':
                o.append('<p>%s</p>' % _inline(blk[1]))
            elif k in ('bullets', 'numbered'):
                tag = 'ul' if k == 'bullets' else 'ol'
                o.append('<%s>%s</%s>' % (tag, ''.join('<li>%s</li>' % _inline(x) for x in blk[1]), tag))
            elif k == 'table':
                o.append(_table_html(blk[1], lang))
            elif k == 'cards':
                o.append('<div class="cards">%s</div>' % ''.join('<div class="card %s"><b>%s</b><span>%s</span></div>' % (
                    e(tone), e(v), e(lbl)) for v, lbl, tone in blk[1]))
            elif k == 'rating':
                o.append('<div class="rating %s"><div class="k">%s</div><div class="v">%s</div></div>' % (e(blk[1]), e(blk[2]), e(blk[3])))
            elif k == 'callout':
                o.append('<div class="callout %s">%s%s</div>' % (e(blk[1]), ('<b>%s</b>' % e(blk[2])) if blk[2] else '', _inline(blk[3])))
            elif k == 'finding':
                o.append(_finding_html(blk[1], lang))
            elif k == 'gantt':
                o.append(_gantt_html(blk[1], lang))
        o.append('<div class="footer-note">%s · %s · %s %s · %s</div></section>' % (
            e(m['doc_id']), e(m['classification']), e(t('version', lang)), e(m['version']), e(fmt_date(m['date'], lang))))
    o.append('</body></html>\n')
    return ''.join(o)


def _md(s):
    s = '' if s is None else str(s)
    return s.replace('|', '\\|').replace('\n', ' ').replace('<', '&lt;').replace('>', '&gt;')


def render_md(doc):
    lang, m = doc['lang'], doc['meta']
    o = ['# %s' % doc['title'], '', '_%s_' % doc['subtitle'], '',
         '| | |', '| --- | --- |']
    for k, v in ((t('client', lang), m['client']), (t('project', lang), m['project']), (t('doc_id', lang), m['doc_id']),
                 (t('version', lang), '%s — %s' % (m['version'], t('draft', lang))), (t('date', lang), fmt_date(m['date'], lang)),
                 (t('prepared_by', lang), m['prepared_by']), (t('classification', lang), m['classification'])):
        o.append('| %s | %s |' % (_md(k), _md(v)))
    o += ['', '> %s' % _md(t('conf_note', lang)), '', '## %s' % t('contents', lang), '']
    secs = _sections_numbered(doc)
    for n, s in secs:
        o.append('%s %s' % ('%d.' % n if n else '-', s['title']))
    for n, s in secs:
        o += ['', '## %s%s' % ('%d. ' % n if n else '', s['title']), '']
        for blk in s['blocks']:
            k = blk[0]
            if k == 'h3':
                o += ['### %s' % blk[1], '']
            elif k == 'p':
                o += [_md(blk[1]), '']
            elif k == 'bullets':
                o += ['- %s' % _md(x) for x in blk[1]] + ['']
            elif k == 'numbered':
                o += ['%d. %s' % (i, _md(x)) for i, x in enumerate(blk[1], 1)] + ['']
            elif k == 'table':
                spec = blk[1]
                o.append('| %s |' % ' | '.join(_md(h) for h in spec['head']))
                o.append('|%s|' % '|'.join(' --- ' for _ in spec['head']))
                for row in spec['rows']:
                    cells = []
                    for i, c in enumerate(row):
                        if isinstance(c, tuple):
                            c = c[1]
                        elif spec.get('sev') == i and c in SEV:
                            c = '**%s**' % t(c, lang)
                        cells.append(_md(c))
                    o.append('| %s |' % ' | '.join(cells))
                o.append('')
            elif k == 'cards':
                o += ['| %s |' % ' | '.join(_md(lbl) for _, lbl, _ in blk[1]), '|%s|' % '|'.join(' --- ' for _ in blk[1]),
                      '| %s |' % ' | '.join('**%s**' % _md(v) for v, _, _ in blk[1]), '']
            elif k == 'rating':
                o += ['**%s: %s**' % (_md(blk[2]), _md(blk[3])), '']
            elif k == 'callout':
                o += ['> %s%s' % (('**%s** — ' % _md(blk[2])) if blk[2] else '', _md(blk[3])), '']
            elif k == 'finding':
                f = blk[1]
                o += ['### %s — %s (%s)' % (f['id'], _md(f['title']), t(f['severity'], lang)), '',
                      '- **%s:** %s' % (t('category', lang), _md(f['cat_label'])),
                      '- **%s:** %s' % (t('affected', lang), _md(', '.join(f['affected']) or '-'))]
                o.append('- **%s:**' % t('observation', lang))
                o += ['  - %s' % _md(x) for x in f['observation']]
                if f['evidence']:
                    o.append('- **%s:**' % t('evidence', lang))
                    o += ['  - %s' % _md(x) for x in f['evidence']]
                o.append('- **%s:** %s' % (t('impact', lang), _md(f['impact'])))
                o.append('- **%s:**' % t('recommendation', lang))
                o += ['  - %s' % _md(x) for x in f['recommendation']]
                o.append('- **%s:** %s' % (t('effort', lang), _hrs(f['effort'][0], f['effort'][1], lang)))
                if f.get('due'):
                    o.append('- **%s:** %s' % (t('due', lang), fmt_date(f['due'], lang)))
                o.append('')
            elif k == 'gantt':
                g = blk[1]
                width = 40
                total = max(1, g['total'])
                o.append('```')
                for lbl, a, b2, _ in g['rows']:
                    s0 = int(round(width * a / total))
                    s1 = max(s0 + 1, int(round(width * b2 / total)))
                    o.append('%-34s |%s%s%s|' % (lbl[:34], ' ' * s0, '█' * (s1 - s0), ' ' * (width - s1)))
                o += ['```', '']
    o += ['', '---', '_%s · %s · %s %s · %s_' % (m['doc_id'], m['classification'], t('version', lang), m['version'],
                                                  fmt_date(m['date'], lang))]
    return '\n'.join(o) + '\n'


def write(doc, path):
    """HTML or Markdown from the extension; temp file + rename, never through a symlink."""
    text = render_html(doc) if os.path.splitext(path)[1].lower() in ('.html', '.htm') else render_md(doc)
    d = os.path.dirname(os.path.abspath(path))
    tmp = os.path.join(d, '.%s.tmp-%d' % (os.path.basename(path), os.getpid()))
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644)
    with os.fdopen(fd, 'w', encoding='utf-8') as f:
        f.write(text)
    os.replace(tmp, path)
    return path


