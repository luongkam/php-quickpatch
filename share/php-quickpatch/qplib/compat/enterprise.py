def t(key, lang, **kw):
    s = (T.get(key) or {}).get(lang) or (T.get(key) or {}).get('en') or key
    for k, v in kw.items():
        s = s.replace('{%s}' % k, str(v))
    return s


def fmt_date(s, lang):
    if not s:
        return '-'
    d = datetime.date(*map(int, s[:10].split('-')))
    return d.strftime('%d/%m/%Y') if lang == 'vi' else d.strftime('%d %b %Y')


def _add_days(s, n):
    return (datetime.date(*map(int, s[:10].split('-'))) + datetime.timedelta(days=n)).isoformat()


def _hrs(lo, hi, lang):
    f = lambda x: ('%.1f' % x).rstrip('0').rstrip('.')   # noqa: E731
    return t('hours', lang, a=f(lo), b=f(hi))


def _pd(lo, hi, lang):
    f = lambda x: ('%.1f' % max(0.5, round(x / 4.0) / 2.0)).rstrip('0').rstrip('.')   # noqa: E731  (half days)
    return t('pdays', lang, a=f(lo), b=f(hi))


def meta_of(res, opts, kind, lang):
    """Document metadata: --client, --project-name, --prepared-by, --classification, --doc-version."""
    opts = opts or {}
    date = (res.get('lifecycle') or {}).get('today') or res['generated_at'][:10]
    project = opts.get('project') or os.path.basename((res.get('paths') or ['project'])[0].rstrip('/')) or 'project'
    slug = re.sub(r'[^A-Za-z0-9]+', '-', project).strip('-').upper()[:24] or 'PROJECT'
    cls = opts.get('classification') or ('MẬT — CONFIDENTIAL' if lang == 'vi' else 'CONFIDENTIAL')
    return {'client': opts.get('client') or '-', 'project': project,
            'prepared_by': opts.get('prepared_by') or 'php-quickpatch', 'classification': cls,
            'version': opts.get('version') or '1.0', 'date': date,
            'doc_id': '%s-%s-%s' % ('SPA' if kind == 'security' else 'RCA', slug, date.replace('-', '')),
            'tool': VERSION, 'catalog': res.get('catalog_version') or '-',
            'bundle': (res.get('lifecycle') or {}).get('bundle_id') or '-'}


