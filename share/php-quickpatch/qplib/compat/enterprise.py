def _matrix(res, lang):
    rows = []
    for p in res['projects']:
        d = p.get('deploy') or {}
        lam = d.get('kind') == 'lambda'
        nd = sum(1 for x in p['declarations'] if x['to_change']) + (len(d.get('functions') or []) if lam else 0)
        hits_e = sum(1 for h in p['hits'] if h['level'] == 'error')
        hits = len(p['hits'])
        eng = sum(1 for v in p['npm_engine_violations'] if v.get('severity') == 'error')
        nat = p['native_addons']
        sdk = [x for x in p['deprecated'] if x['package'] == 'aws-sdk']

        def st(key, n=0):
            return (key, t(key, lang, n=n))
        rows.append([BR.pname(p),
                     st('st_change', nd) if nd else st('st_ok'),
                     st('st_unknown') if not p['current_branch'] else (st('st_block', hits_e) if hits_e else (st('st_change', hits) if hits else st('st_ok'))),
                     st('st_block', eng) if eng else st('st_ok'),
                     (st('st_block', sum(1 for a in nat if a['load_ok'] is False)) if any(a['load_ok'] is False for a in nat)
                      else (st('st_change', len(nat)) if nat else st('st_na'))),
                     st('st_change', sum(len(s['sites']) for x in sdk for s in x.get('services') or []) + sum(x.get('promise_calls') or 0 for x in sdk)) if sdk else st('st_na'),
                     st('st_ok') if p.get('has_tests') else (st('st_missing') if d.get('kind') != 'static_site' else st('st_na'))])
    return rows


def _count_where(decls, fns, lang):
    parts = []
    if fns:
        parts.append(('%d AWS Lambda functions' if lang == 'en' else '%d function AWS Lambda') % len(fns))
    if decls:
        parts.append(('%d places in the code' if lang == 'en' else '%d vị trí trong mã') % len(decls))
    return ', '.join(parts)


