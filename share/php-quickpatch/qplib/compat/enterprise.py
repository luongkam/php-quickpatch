def security_findings(res, lang, b):
    """Findings of the security posture assessment, most severe first, with IDs SEC-01..."""
    lc = res.get('lifecycle') or {}
    final, today = b['final_target'], (lc.get('today') or res['generated_at'][:10])
    fe = (lc.get('target') or {}).get('eol_date') if final == res['target_branch'] else lc.get('recommended_eol')
    eff = {r['kind']: r['hours'] for r in b['effort']['rows']}
    fns = [f for p in res['projects'] for f in (p.get('deploy') or {}).get('functions') or []]
    out = []
    cur = res.get('current_branch')
    rk = {r['key']: r for r in b['risks']}
    if cur:
        c = lc.get('current') or {}
        lam = rk.get('r_lambda_deprecated') or rk.get('r_lambda_blocked') or rk.get('r_lambda_soon')
        obs = [t('o_runtime', lang, c=cur, e=fmt_date(c.get('eol_date'), lang))] if c.get('status') == 'EOL' else []
        if lam:
            a = lam['args']
            obs.append(t('o_lambda', lang, c=cur, dep=fmt_date(a['dep'], lang), os=a['os'], bc=fmt_date(a['bc'], lang),
                         bu=fmt_date(a['bu'], lang), n=a['n']))
            if a['os'] == 'Amazon Linux 2' and today >= BR.AL2_EOL:
                obs.append(t('o_al2', lang, e=fmt_date(BR.AL2_EOL, lang)))
            if any(k == 'r_lambda_console' for k, _ in lam['more']):
                obs.append(t('o_console', lang))
        if obs:
            sev = lam['level'] if lam else (rk.get('r_runtime_eol') or {}).get('level', 'high')
            lo, hi = eff.get('lambda_runtime_switch', [0, 0])
            l2, h2 = eff.get('runtime_declarations', [0, 0])
            out.append({'title': t('f_runtime' if lam else 'f_runtime_node', lang, c=cur), 'severity': sev,
                        'category': 'platform', 'affected': fns or [x['name'] for x in _assets(res)],
                        'observation': obs,
                        'evidence': ['Node.js %s: EOL %s; latest %s' % (cur, c.get('eol_date') or '?', c.get('latest') or '?')] +
                                    (['AWS Lambda nodejs%s.x: deprecation %s, block create %s, block update %s (%s, %s)' % (
                                        cur, lam['args']['dep'], lam['args']['bc'], lam['args']['bu'], BR.LAMBDA_SOURCE,
                                        BR.LAMBDA_AS_OF)] if lam else []),
                        'impact': t('i_runtime', lang, bu=fmt_date(lam['args']['bu'], lang) if lam else '-', c=cur),
                        'recommendation': [x.replace('{t}', final).replace('{e}', fmt_date(fe, lang)) for x in T['r_runtime'][lang]],
                        'effort': [lo + l2 + 2, hi + h2 + 4], 'refs': [BR.LAMBDA_SOURCE, 'https://nodejs.org/en/about/previous-releases']})
    elif 'r_runtime_unknown' in rk:
        out.append({'title': t('f_unknown', lang), 'severity': 'high', 'category': 'platform', 'affected': fns,
                    'observation': [t('o_unknown', lang, n=len(fns))], 'evidence': ['deploy scripts: aws lambda update-function-code'],
                    'impact': t('i_unknown', lang), 'recommendation': T['r_unknown'][lang], 'effort': [0.5, 1], 'refs': []})
    vul = _vulns(res)
    prod = [(k, x) for k, x in vul.items() if x['scope'] == 'prod']
    group = {'medium': [], 'low': []}
    for (p, v), x in sorted(prod, key=lambda kv: (_rank(kv[1]['v']['severity']), kv[0])):
        vv = x['v']
        sev = 'critical' if vv.get('in_kev') or vv.get('is_malware') else vv['severity']
        if sev in group:
            group[sev].append((p, v, x))
            continue
        path = t('direct', lang) if not vv.get('via') else t('via', lang, x=', '.join(vv['via']))
        rec = [t('r_pkg', lang, p=p, f=vv['fix_version'])] if vv['fix_version'] else [t('r_pkg_nofix', lang)]
